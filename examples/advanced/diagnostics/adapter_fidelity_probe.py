"""H9: train-only data-path audit. Stop actual adapter/Fedot before model search.

No estimator training, outer-test access, cache changes or benchmark reruns.
Prepared pandas pickle is trusted, generated by this script in a new stage.
"""
import argparse
import hashlib
import importlib.util
import json
from pathlib import Path
import time
from types import SimpleNamespace
from unittest.mock import patch

import numpy as np


def sha(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def write(path, value):
    with Path(path).open('x', encoding='utf8') as f:
        json.dump(value, f, indent=2, allow_nan=False)


def compare_arrays(left, right):
    a, b = np.asarray(left), np.asarray(right)
    result = {'shape_left': list(a.shape), 'shape_right': list(b.shape),
              'dtype_left': str(a.dtype), 'dtype_right': str(b.dtype)}
    if a.shape != b.shape:
        return dict(result, equal=False, equal_float32=False, max_abs=None)
    a, b = a.astype(float), b.astype(float)
    finite = np.isfinite(a) & np.isfinite(b)
    return dict(result, equal=bool(np.array_equal(a, b, equal_nan=True)),
                equal_float32=bool(np.array_equal(a.astype('float32'), b.astype('float32'), equal_nan=True)),
                max_abs=float(np.max(np.abs(a[finite] - b[finite]))) if finite.any() else 0.,
                same_nonfinite=bool(np.array_equal(np.isnan(a), np.isnan(b)) and
                                    np.array_equal(np.isinf(a), np.isinf(b))))


def prepare(stage, cache):
    import openml
    from sklearn.preprocessing import LabelEncoder
    setter = getattr(openml.config, 'set_root_cache_directory', openml.config.set_cache_directory)
    setter(str(cache))
    task = openml.tasks.get_task(168910, download_data=False)
    dataset = task.get_dataset()
    frame, target, categorical, names = dataset.get_data(target=task.target_name, dataset_format='dataframe')
    rows, _ = task.get_train_test_split_indices(fold=6)
    # Discard outer test before any transformation or serialization.
    frame = frame.iloc[rows].copy()
    y = LabelEncoder().fit_transform(np.asarray(target)[rows])
    del target
    with np.load(stage / 'train.npz', allow_pickle=False) as z:
        check = compare_arrays(frame.to_numpy(), z['features'])
        assert check['equal_float32'] and check['same_nonfinite'], check
        assert np.array_equal(y, z['target'].ravel())
    with (stage / 'train-frame.pkl').open('xb') as f:
        frame.to_pickle(f)
    with (stage / 'train-frame-target.npz').open('xb') as f:
        np.savez_compressed(f, target=y, original_train_rows=rows)
    write(stage / 'preparation.json', dict(task=168910, fold=6, rows=len(rows),
          shape=list(frame.shape), categorical_count=sum(categorical),
          feature_names=list(names), dtype_counts={str(k):int(v) for k,v in frame.dtypes.value_counts().items()},
          float32_comparison=check, frame_sha256=sha(stage/'train-frame.pkl'),
          target_sha256=sha(stage/'train-frame-target.npz'), npz_sha256=sha(stage/'train.npz')))


class CapturedBeforeSearch(Exception):
    pass


def capture(adapter, features, target):
    """Call the REAL adapter.run and REAL Fedot.fit; only intercept model search."""
    from fedot.core.pipelines.pipeline import Pipeline
    original = adapter.Fedot
    captured = {}

    def factory(*args, **kwargs):
        automl = original(*args, **kwargs)
        def stop(data):
            captured['data'] = data
            captured['params'] = {k: automl.params.get(k) for k in
                                  ('use_input_preprocessing', 'use_auto_preprocessing', 'cv_folds')}
            raise CapturedBeforeSearch()
        automl.api_composer.obtain_model = stop
        return automl

    config = SimpleNamespace(type='classification', metric='logloss', cores=8, seed=104735,
                             max_runtime_seconds=3600,
                             framework_params={'preset':'best_quality', 'with_tuning':True,
                                               'final_fit_use_remaining_time':False, '_portfolio':False})
    # Adapter reads test.y before fit. This empty placeholder contains no outer data.
    dataset = SimpleNamespace(train=SimpleNamespace(X=features, y=target),
                              test=SimpleNamespace(y=np.empty(0, dtype=int)))
    with patch.object(adapter, 'Fedot', factory), patch.object(
            Pipeline, 'fit', side_effect=AssertionError('H9 forbids pipeline training')):
        try:
            adapter.run(dataset, config)
        except CapturedBeforeSearch:
            pass
    if 'data' not in captured:
        raise AssertionError('Adapter did not reach expected pre-composition boundary')
    return captured


def summarize(data):
    return dict(shape=list(data.features.shape), dtype=str(data.features.dtype),
                target_shape=list(data.target.shape),
                numerical_idx=np.asarray(data.numerical_idx).tolist(),
                categorical_idx=np.asarray(data.categorical_idx).tolist(),
                supplementary={k:np.asarray(getattr(data.supplementary_data,k)).tolist() for k in
                               ('is_auto_preprocessed','was_preprocessed','optionally_preprocessed')
                               if hasattr(data.supplementary_data,k)})


def run(stage):
    import pandas as pd
    from fedot.core.data.data import InputData
    from fedot.core.repository.tasks import Task, TaskTypesEnum
    from fedot.core.repository.dataset_types import DataTypesEnum
    manifest = json.loads((stage/'manifest.json').read_text())
    for name, expected in manifest['files'].items():
        assert sha(stage/name) == expected, name
    write(stage/'STARTED', {'utc':time.strftime('%Y-%m-%dT%H:%M:%SZ', time.gmtime())})
    started = time.monotonic()
    try:
        path = stage/'harness/frameworks/FEDOT/exec.py'
        spec = importlib.util.spec_from_file_location('h9_actual_adapter', path)
        adapter = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(adapter)
        frame = pd.read_pickle(stage/'train-frame.pkl')
        with np.load(stage/'train.npz', allow_pickle=False) as z:
            x, y = z['features'].copy(), z['target'].copy()
        raw = InputData(idx=np.arange(len(y)), features=x.copy(), target=y.copy(),
                        task=Task(TaskTypesEnum.classification), data_type=DataTypesEnum.table)
        api32 = capture(adapter, x.copy(), y.copy())
        api_frame = capture(adapter, frame.copy(), y.copy())
        arrays = dict(raw_features=x, raw_target=y, raw_idx=raw.idx)
        for label, captured in [('api32',api32),('api_frame',api_frame)]:
            data = captured['data']
            arrays.update({label+'_features':np.asarray(data.features, dtype=float),
                           label+'_target':np.asarray(data.target).ravel(), label+'_idx':np.asarray(data.idx)})
            assert np.array_equal(data.idx, raw.idx), 'row order changed'
            assert np.array_equal(np.asarray(data.target).ravel(), y.ravel()), 'target order changed'
        with (stage/'representations.npz').open('xb') as f:
            np.savez_compressed(f, **arrays)
        result = dict(raw=summarize(raw),api32=summarize(api32['data']),
                      api_frame=summarize(api_frame['data']), params=api_frame['params'],
                      raw_vs_api32=compare_arrays(x,api32['data'].features),
                      api32_vs_frame=compare_arrays(api32['data'].features,api_frame['data'].features),
                      seconds=time.monotonic()-started, model_fits=0,
                      representations_sha256=sha(stage/'representations.npz'))
        write(stage/'result.json',result)
        write(stage/'COMPLETE',{'utc':time.strftime('%Y-%m-%dT%H:%M:%SZ',time.gmtime())})
        print(json.dumps(result))
    except BaseException as error:
        write(stage/'FAILED',{'error':repr(error)})
        raise


if __name__ == '__main__':
    parser=argparse.ArgumentParser()
    parser.add_argument('mode',choices=['prepare','run'])
    parser.add_argument('--stage',type=Path,required=True)
    parser.add_argument('--cache',type=Path)
    args=parser.parse_args()
    (prepare(args.stage,args.cache) if args.mode=='prepare' else run(args.stage))
